"""Writes data/palmistry-rules.json and research/palmistry-rulebook.md from rules_data.py"""
import json, collections, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rules_data as R
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '../..'))

def counts():
    c = collections.Counter(f['kind'] for f in R.ALL_FEATURES)
    return dict(c)

doc = dict(
    schema_version=1,
    title="Hast Rekha rulebook (Samudrika / Western palmistry synthesis)",
    purpose="Machine-readable palmistry rules for the Hast Rekha Quest app: what each line, mount, hand shape, finger and mark means, which measurable attribute changes the reading, and where the rule comes from.",
    disclaimer="Palmistry is a cultural and entertainment tradition, widely regarded as pseudoscience, with many conflicting interpretations (S9). The app must present readings as 'the tradition says...', never as prediction, diagnosis or advice. Many source rules (death, illness, insanity, infidelity, fertility) are recorded for completeness but flagged 'sensitivity' and must not be shown.",
    citation_levels=dict(read="I read the passage; the rule is a paraphrase of it", toc="section confirmed from the table of contents; the rule is standard teaching consistent with that section but not line-verified", web="modern web page, facts only"),
    conventions=dict(
        page_numbers="S1 page numbers are the printed page where the section starts (from the book's contents list). S2 is cited by Part and chapter because the OCR page numbers are unreliable.",
        text_policy="All wording is paraphrased. No source text is reproduced.",
        naming="Hindi/Sanskrit names are given where known. Where sources disagree (e.g. pitru/matru/ayu), the primary label is the one most sources agree on and the others are listed under aliases.",
        region_ref="Each feature that lives on the palm points to data/palm-regions.json for its joint-space region.",
        app_policy_fields="app_safe_reading = what the app may say; avoid_claims = what it must not say; sensitivity = category tags to filter on.",
        hands="Cheiro: left hand = inherited tendencies, right = developed. Modern Indian guides: dominant hand = present, other = innate (S7). Do not use the old 'men right, women left' rule (S7 calls it 'bunkum').",
    ),
    sources=R.SOURCES,
    feature_counts=counts(),
    total_features=len(R.ALL_FEATURES),
    features=R.ALL_FEATURES,
    not_found=[
        "No open-source JSON/YAML rule set encoding line or mount meanings was found. Checked: GitHub repository search for 'palmistry' (30 results), openoccult/openoccult-data (tarot/runes/crystals; no palmistry file in its 78-file tree), SpandanM110/Local-First-AI-Astrologer (uses Cheiro's book as a RAG source, ships no rules), himajin315/palmistry (MIT, Japanese rule-to-text site; not reviewed in depth).",
        "No public-domain English translation of a Sanskrit 'Hasta Samudrika' manual was found. The usable Indian primary material is verse-level (Brihat Samhita 68; Agni, Garuda, Bhavishya, Vishnudharmottara Puranas via S4/S5).",
    ],
)
json.dump(doc, open(os.path.join(ROOT, 'data/palmistry-rules.json'), 'w'), indent=1, ensure_ascii=False)

# ---------------- markdown ----------------
L = []
w = L.append
w("# Hast Rekha rulebook\n")
w("Readable version of [`data/palmistry-rules.json`](../data/palmistry-rules.json) (generated by `scripts/palm/build_rulebook.py`; edit `scripts/palm/rules_data.py`, not this file).\n")
w(f"**{len(R.ALL_FEATURES)} features:** " + ", ".join(f"{v} {k}s" for k, v in counts().items()) + ".\n")
w("> Palmistry is a cultural / entertainment tradition, widely viewed as pseudoscience with many conflicting readings. The app says \"the tradition says…\" and never predicts, diagnoses or advises. Rules about death, illness, insanity, infidelity or fertility are recorded but flagged and **must not be shown**.\n")
w("## How to read the citations\n")
w("- `read`: I read the passage and paraphrased it.\n- `toc`: section confirmed from the book's table of contents; the rule is standard teaching consistent with it, **not line-verified**.\n- `web`: modern web page, facts only.\n- S1 pages are printed page numbers of the section start; S2 (Benham) is cited by Part/chapter.\n")
w("## Sources and licences\n")
w("| ID | Source | Licence / status | Used for |\n|---|---|---|---|")
for s in R.SOURCES:
    w(f"| {s['id']} | [{s['title']}]({s['url']}) — {s['author']}, {s['year']} | {s['licence']} | {s['used_for']} |")
w("")
w("**Not found:** " + " ".join(doc['not_found']) + "\n")
w("**Important Indian-tradition note.** The classical Indian texts (S3, S4, S5) read the palm through a few described lines and above all *auspicious marks* (fish, conch, wheel, lotus, flag, swastika…). The heart/head lines and the planetary mounts (parvat) of modern hast-rekha come from the Western Cheiro/Benham tradition and were absorbed into Indian practice in the 20th century (S5 states the names do not occur in the classical texts; S6 follows the Western system). Cultural framing in the app should respect that: the 'shubh chinh' (auspicious marks) layer is the genuinely classical part.\n")

def block(f):
    w(f"### {f['name_en']}" + (f" — {f['name_hi']}" if f['name_hi'] not in ('-', None) else "") + (f" ({f['name_roman']})" if f['name_roman'] not in ('-', None) else ""))
    w(f"`{f['id']}` · confidence **{f['confidence']}**" + (f" · tier {f['tier']}" if f.get('tier') else ""))
    w("")
    w(f['summary'] + "\n")
    if f['aliases']:
        w("Aliases: " + "; ".join(f"{a['hi']} ({a['roman']})" + (f" — {a['note']}" if a.get('note') else "") for a in f['aliases']) + "\n")
    if f.get('note'): w(f"*Note:* {f['note']}\n")
    if f['attributes']:
        w("| Attribute | Value | Effect on the reading | Cite |\n|---|---|---|---|")
        for a in f['attributes']:
            for v in a['values']:
                c = v['cite']
                cs = f"{c['src']}: {c['loc']} [{c['level']}]" if c else ""
                w(f"| {a['attribute']} | {v['value']} | {v['effect']} | {cs} |")
        w("")
    w("Sources: " + "; ".join(f"{c['src']} {c['loc']} [{c['level']}]" for c in f['citations']) + "\n")
    if f.get('app_safe_reading'): w(f"- **App may say:** {f['app_safe_reading']}")
    if f['avoid_claims']: w(f"- **App must not say:** {'; '.join(f['avoid_claims'])}" + (f" (sensitivity: {', '.join(f['sensitivity'])})" if f['sensitivity'] else ""))
    if f.get('region_ref'): w(f"- **Region:** `{f['region_ref']}`")
    if f.get('auto_detect'): w(f"- **Auto-detect:** {f['auto_detect']}")
    w("")

for title, kinds in [("Lines (rekha)", ['line', 'line-attribute']), ("Mounts (parvat)", ['mount', 'mount-attribute']), ("Hand shapes", ['hand-shape']), ("Fingers and thumb", ['finger']), ("Marks (chinh), including the classical auspicious marks", ['mark'])]:
    w(f"## {title}\n")
    for f in R.ALL_FEATURES:
        if f['kind'] in kinds: block(f)
open(os.path.join(ROOT, 'research/palmistry-rulebook.md'), 'w').write("\n".join(L))
print(json.dumps(doc['feature_counts']), doc['total_features'])
