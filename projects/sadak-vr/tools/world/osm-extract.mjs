// Dev-only: cut the parts of SADAK's compiled Purani Sadak map (Chandni Chowk,
// Old Delhi) that Sadak VR's six spots can see, and write them as a TS module.
//
//   node tools/world/osm-extract.mjs [path/to/purani-sadak.json]
//
// Source: sadak-source/game_engine/public/maps/purani-sadak.json, compiled by
// SADAK's scripts/osm/build.ts from OpenStreetMap (roads with their real
// widths, real building footprints, and the building plots SADAK lays along
// every frontage). Map data (c) OpenStreetMap contributors, ODbL 1.0.
// Frame: metres from the map centre, +x east, +z south.
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = process.argv[2] ?? new URL('../../../../../../sadak-source/game_engine/public/maps/purani-sadak.json', import.meta.url).pathname;
const OUT = new URL('../../src/world/osm-data.ts', import.meta.url).pathname;
const map = JSON.parse(readFileSync(SRC, 'utf8'));

// Counter positions of the six spots (see src/world/layout.ts SPOTS).
const CENTRES = [
  [3.45, -313.3], // kachori, Dariba Kalan corner
  [219.3, -304.6], // flowers, Gauri Shankar temple
  [-3.9, -100.7], // auto, Dariba Kalan
  [282.0, -90.9], // bus, Lal Quila stop
  [-277.1, -326.1], // paranthe, Paranthe Wali Gali
  [72.4, 277.0], // minaret, Jama Masjid east steps
];
const R = 165;
const near = (x, z, r = R) => CENTRES.some(([cx, cz]) => Math.hypot(x - cx, z - cz) < r);
const segNear = (a, b, r = R) =>
  CENTRES.some(([cx, cz]) => {
    const dx = b[0] - a[0];
    const dz = b[1] - a[1];
    const L = dx * dx + dz * dz || 1;
    const t = Math.max(0, Math.min(1, ((cx - a[0]) * dx + (cz - a[1]) * dz) / L));
    return Math.hypot(a[0] + dx * t - cx, a[1] + dz * t - cz) < r;
  });
const r1 = (v) => Math.round(v * 10) / 10;
const pt = (p) => [r1(p[0]), r1(p[1])];

const roads = map.roads
  .filter((r) => r.pts.some((p, i) => i > 0 && segNear(r.pts[i - 1], p)))
  .map((r) => ({ cls: r.cls, w: r.w, foot: r.foot, name: r.name ?? '', surface: r.surface ?? '', a: r.a, b: r.b, pts: r.pts.map(pt) }));
const plots = map.plots.filter((p) => near(p.x, p.z)).map((p) => [r1(p.x), r1(p.z), Math.round(p.rot * 1000) / 1000, r1(p.w), r1(p.d), p.floors, p.front ? 1 : 0, p.seed % 100000]);
const buildings = map.buildings
  .filter((b) => b.pts.some((p) => near(p[0], p[1], R + 30)) && b.name !== 'Jama Masjid')
  .map((b) => ({ h: b.h, pts: b.pts.map(pt) }));
const areas = map.areas.filter((a) => a.pts.some((p) => near(p[0], p[1], R + 60))).map((a) => ({ kind: a.kind, pts: a.pts.map(pt) }));
const landmarks = map.landmarks.map((l) => ({ model: l.model, name: l.name, x: l.x, z: l.z, rot: l.rot, w: l.w, d: l.d, door: l.door ?? null }));

const body = `/**
 * Old Delhi around Sadak VR's six spots: the real street network, building
 * footprints and frontage plots of Chandni Chowk, Dariba Kalan, Paranthe Wali
 * Gali, Netaji Subhash Marg and the Jama Masjid's east side.
 *
 * GENERATED by tools/world/osm-extract.mjs from SADAK's compiled map
 * (sadak-source/game_engine/public/maps/purani-sadak.json, built by SADAK's
 * scripts/osm/build.ts from OpenStreetMap). Do not edit by hand.
 *
 * Map data (c) OpenStreetMap contributors, ODbL 1.0
 * (https://www.openstreetmap.org/copyright).
 *
 * Frame: metres from SADAK's map centre, +x east, +z south.
 */

export type OsmRoad = { cls: string; w: number; foot: number; name: string; surface: string; a: number; b: number; pts: [number, number][] };
/** [x, z, rot, w, d, floors, front (1 = street frontage), seed]; local +z faces the street along (sin rot, cos rot). */
export type OsmPlot = [number, number, number, number, number, number, number, number];
export type OsmBuilding = { h: number; pts: [number, number][] };
export type OsmArea = { kind: string; pts: [number, number][] };
export type OsmLandmark = { model: string; name: string; x: number; z: number; rot: number; w: number; d: number; door: [number, number] | null };

export const OSM_ATTRIBUTION = 'Map data \\u00a9 OpenStreetMap contributors, ODbL 1.0';
export const ROADS: OsmRoad[] = ${JSON.stringify(roads)};
export const PLOTS: OsmPlot[] = ${JSON.stringify(plots)};
export const BUILDINGS: OsmBuilding[] = ${JSON.stringify(buildings)};
export const AREAS: OsmArea[] = ${JSON.stringify(areas)};
export const LANDMARKS: OsmLandmark[] = ${JSON.stringify(landmarks)};
`;
writeFileSync(OUT, body);
console.log(`roads ${roads.length}, plots ${plots.length}, buildings ${buildings.length}, areas ${areas.length} -> ${OUT} (${Math.round(body.length / 1024)} KB)`);
